package sealmc.swe3tie.sealcore;

import io.papermc.paper.plugin.loader.PluginClasspathBuilder;
import io.papermc.paper.plugin.loader.PluginLoader;
import io.papermc.paper.plugin.loader.library.impl.MavenLibraryResolver;
import org.eclipse.aether.artifact.DefaultArtifact;
import org.eclipse.aether.graph.Dependency;
import org.eclipse.aether.repository.RemoteRepository;
import org.jetbrains.annotations.NotNull;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;

/**
 * Resolves runtime libraries (HikariCP, JDBC drivers) through Paper's library loader, so they are
 * downloaded once by the server instead of being shaded into the jar.
 * The coordinate list is generated by the build into {@code sealcore-libraries.txt}.
 */
@SuppressWarnings("UnstableApiUsage")
public final class SealCoreLoader implements PluginLoader {

    @Override
    public void classloader(@NotNull PluginClasspathBuilder builder) {
        MavenLibraryResolver resolver = new MavenLibraryResolver();
        resolver.addRepository(new RemoteRepository.Builder(
            "central", "default", MavenLibraryResolver.MAVEN_CENTRAL_DEFAULT_MIRROR).build());

        try (InputStream in = SealCoreLoader.class.getResourceAsStream("/sealcore-libraries.txt")) {
            if (in == null) throw new IllegalStateException("sealcore-libraries.txt missing from jar");
            try (BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
                reader.lines()
                    .map(String::trim)
                    .filter(line -> !line.isEmpty() && !line.startsWith("#"))
                    .forEach(coords -> resolver.addDependency(new Dependency(new DefaultArtifact(coords), null)));
            }
        } catch (IOException e) {
            throw new IllegalStateException("Could not read SealCore library list", e);
        }

        builder.addLibrary(resolver);
    }
}
